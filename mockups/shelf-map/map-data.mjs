// map-data.mjs — dev-only. Reads src/data/paints.json with the REAL engine (src/js) and writes map-data.js,
// the data that mockups/shelf-map.html draws. The page does not import src/js itself, so it also opens as
// a plain file (file:// blocks ES modules). Run: node mockups/shelf-map/map-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { indexDataset, finishClass, GREY_CHROMA } from '../../src/js/data.js';

const here = new URL('.', import.meta.url);
const idx = indexDataset(JSON.parse(readFileSync(new URL('../../src/data/paints.json', here))));

// The catalogue: every paint still made (the gap suggestions come from it). One array per paint, short keys.
const live = idx.paints.filter(p => !p.discontinued);
const r1 = x => Math.round(x * 10) / 10;
const cat = live.map(p => {
  const [L, a, b] = p.lab;
  const C = Math.hypot(a, b), h = (Math.atan2(b, a) * 180 / Math.PI + 360) % 360;
  return [p.dname || p.name, p.brand, p.line, p.hex, p.type, finishClass(p.type), r1(L), r1(a), r1(b), r1(C), r1(h), p.fx || ''];
});
const at = new Map(live.map((p, i) => [p.id, i]));

// A seeded random (mulberry32), so the sample shelves are the same on every run.
function rng(seed) { return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
  t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }

// Shelf 1 — a starter shelf: the Citadel paints a new painter often has (a typical starter set + a few more).
const STARTER = ['Abaddon Black', 'White Scar', 'Mephiston Red', 'Macragge Blue', 'Caliban Green', 'Averland Sunset',
  'Rhinox Hide', 'Mournfang Brown', 'Zandri Dust', 'Leadbelcher', 'Retributor Armour', 'Agrax Earthshade',
  'Nuln Oil', 'Reikland Fleshshade', 'Evil Sunz Scarlet', 'Calgar Blue', 'Warpstone Glow', 'Ushabti Bone',
  'Mechanicus Standard Grey', 'Dawnstone', 'Kantor Blue', "Bugman's Glow", 'Cadian Fleshtone', 'Runefang Steel',
  'Ironbreaker', 'Wazdakka Red', 'Death Guard Green', 'Screamer Pink', 'Balthasar Gold', 'Steel Legion Drab'];
const citadel = idx.paints.filter(p => p.brand === 'Warhammer Colour' && !p.discontinued);
const byName = n => citadel.find(p => p.name === n && (p.line === 'Base' || p.line === 'Shade'))
  || citadel.find(p => p.name === n || (p.formerly || []).includes(n));
const starter = STARTER.map(n => { const p = byName(n); if (!p) throw new Error('no paint ' + n); return p.id; });
const starterBuy = ['Naggaroth Night', 'Thousand Sons Blue', 'Yriel Yellow'].map(n => byName(n)?.id).filter(Boolean);

// Shelf 2 — a grimdark army painter, 220 paints over five brands: heavy on browns, reds, greys, greens and metals,
// light on purples, pinks, cyans and pale tints, as a real shelf is. Weighted by hue so the gaps are real ones.
const rnd = rng(61);
const pool = live.filter(p => ['Warhammer Colour', 'Vallejo', 'Army Painter', 'AK Interactive', 'Pro Acryl'].includes(p.brand));
const weight = p => {
  const [L, a, b] = p.lab; const C = Math.hypot(a, b), h = (Math.atan2(b, a) * 180 / Math.PI + 360) % 360;
  if (p.type === 'metal') return 2.2;
  if (C < GREY_CHROMA) return 1.6;
  let w = 1;
  if (h >= 20 && h < 100) w = 2.4;            // reds, oranges, browns, flesh
  else if (h >= 100 && h < 160) w = 1.3;      // greens, khaki
  else if (h >= 160 && h < 230) w = 0.25;     // teals, cyans
  else if (h >= 230 && h < 280) w = 0.9;      // blues
  else w = 0.15;                              // purples, magentas, pinks
  if (L > 80) w *= 0.3;                       // few pale tints
  return w;
};
const big = new Set();
while (big.size < 220) { const p = pool[Math.floor(rnd() * pool.length)]; if (rnd() < weight(p) / 2.4) big.add(p.id); }
const bigBuy = [];
while (bigBuy.length < 12) { const p = pool[Math.floor(rnd() * pool.length)]; if (!big.has(p.id) && !bigBuy.includes(p.id)) bigBuy.push(p.id); }

const shelf = (name, note, owned, buy) => ({ name, note, owned: owned.map(i => at.get(i)), buy: buy.map(i => at.get(i)) });
const data = {
  generated: new Date().toISOString().slice(0, 10), dataset: idx.version, greyChroma: GREY_CHROMA, cat,
  shelves: [
    shelf('Starter shelf', `${starter.length} Warhammer Colour paints, a typical first set`, starter, starterBuy),
    shelf('Big grimdark shelf', '220 paints over 5 brands, weighted to browns, reds, greys and metals', [...big], bigBuy),
  ],
};
writeFileSync(new URL('map-data.js', here), '// Generated by map-data.mjs — do not edit.\nwindow.MAP_DATA = ' + JSON.stringify(data) + ';\n');
console.log('catalogue', cat.length, 'starter', starter.length, 'big', big.size);
