// engine-data.mjs — dev-only. Runs the REAL engine (src/js) on src/data/paints.json and writes
// engine-data.js, the data that mockups/share-image.html draws. The mockup does not import src/js
// itself, so the page also works as a single published page. Run: node mockups/share-image/engine-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { indexDataset, nearestPaint, FINISH_TYPES, matchQuality } from '../../src/js/data.js';
import { buildScheme } from '../../src/js/scheme.js';
import { harmonize, neutralPartners, isNeutralHarmony, DEFAULT_POP } from '../../src/js/harmony.js';
import { textOn, contrastRatio, labChroma, rgbToHsl, hexToRgb } from '../../src/js/color.js';
import { encodeState } from '../../src/js/share.js';

const here = new URL('.', import.meta.url);
const raw = JSON.parse(readFileSync(new URL('../../src/data/paints.json', here)));
const idx = indexDataset(raw);

// The app's default match options (app.js matchOpts, "Use my paints" off, Include Contrast off).
const OPTS = { ladder: 'wash', excludeTypes: new Set(FINISH_TYPES), demoteTypes: new Set(['metal']), demoteAmount: 4 };

// The stress cases the plan asks for: a plain 4-colour scheme, a neutral seed, a 5-colour harmony,
// a very long paint name, and a metallic pick (finish overlay + icon).
const CASES = [
  { key: 'red', label: 'Mephiston Red · split-complementary', id: 'citadel-base-mephiston-red', harmony: 'split-complementary' },
  { key: 'neutral', label: 'Abaddon Black · neutral + pop (a neutral seed)', id: 'citadel-base-abaddon-black', harmony: 'neutral-pop' },
  { key: 'five', label: 'Caliban Green · square (5 colours on the live palette)', name: 'Caliban Green', harmony: 'square' },
  { key: 'long', label: 'A very long name · analogous', name: 'Xb-518 Zashchitniy Zeleno (russian Postwar Green)', harmony: 'analogous' },
  { key: 'metal', label: 'Retributor Armour · complementary (a metallic pick)', id: 'citadel-base-retributor-armour', harmony: 'complementary' },
];

const paintOut = m => m && {
  id: m.paint.id, name: m.paint.dname || m.paint.name, brand: m.paint.brand, line: m.paint.line,
  hex: m.paint.hex, type: m.paint.type, fx: m.paint.fx || null,
  dE: Math.round(m.deltaE * 10) / 10, label: matchQuality(m.deltaE).label, tier: matchQuality(m.deltaE).tier,
  ink: textOn(m.paint.hex), inkRatio: Math.round(contrastRatio(textOn(m.paint.hex), m.paint.hex) * 100) / 100,
};

const out = CASES.map(c => {
  const seed = c.id ? idx.byId.get(c.id) : idx.paints.find(p => p.name === c.name);
  if (!seed) throw new Error('no paint ' + (c.id || c.name));
  const scheme = buildScheme(idx, seed.hex, c.harmony, { ...OPTS, seed: { id: seed.id, hex: seed.hex, name: seed.name } });
  const rule = isNeutralHarmony(c.harmony)
    ? [{ hex: seed.hex, deg: 0 }, ...neutralPartners(seed.hex, DEFAULT_POP, c.harmony)]
    : harmonize(seed.hex, c.harmony);
  const roleByHex = Object.fromEntries(scheme.roles.map(r => [r.idealHex.toUpperCase(), r.role]));
  const live = rule.map(n => {
    const m = nearestPaint(idx, n.hex, n.hex === seed.hex ? { ...OPTS, preferIds: new Set([seed.id]) } : OPTS);
    return { ideal: n.hex, hue: Math.round(rgbToHsl(hexToRgb(n.hex))[0]), deg: n.deg ?? null,
      role: roleByHex[n.hex.toUpperCase()] || null, pot: paintOut(m) };
  });
  const q = encodeState({ baseId: seed.id, pickHex: seed.hex, harmony: c.harmony });
  return {
    key: c.key, label: c.label, harmony: c.harmony,
    seed: { id: seed.id, name: seed.dname || seed.name, brand: seed.brand, line: seed.line, hex: seed.hex, type: seed.type,
      chroma: Math.round(labChroma(seed.hex) * 10) / 10 },
    url: 'https://palette.ryanmette.com/?' + q.toString(),
    live,
    roles: scheme.roles.map(r => ({
      role: r.role, weight: r.weight, ideal: r.idealHex, pot: paintOut(r.match),
      ladder: r.ladders[r.ladders.length - 1].steps.map(s => ({ key: s.key, ideal: s.idealHex, dilute: !!s.dilute, pot: paintOut(s.match) })),
      ladderLabel: r.ladders[r.ladders.length - 1].label,
      temp: r.ladders[0].style === 'temp',
    })),
  };
});

// The four paints on today's static link card (src/og-image.png), for the safe-zone redraw.
const OG = ['Mephiston Red', 'Skrag Brown', 'Hydra Turquoise', 'Keleshite Gold'].map(n => {
  const p = idx.paints.find(q => q.name === n);
  return { name: p.name, brand: p.brand, hex: p.hex, type: p.type, fx: p.fx || null, ink: textOn(p.hex) };
});

const banner = `// Generated by engine-data.mjs from paints.json ${raw.version} (${raw.paints.length} paints) on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n`;
writeFileSync(new URL('engine-data.js', here), banner + 'window.SHARE_DATA = ' + JSON.stringify({ dataset: raw.version, paints: raw.paints.length, og: OG, cases: out }, null, 1) + ';\n');
for (const c of out) console.log(c.key, c.url, '\n  live:', c.live.map(l => (l.role || '-') + ':' + l.pot.name + ' ΔE' + l.pot.dE).join(' | '), '\n  roles:', c.roles.map(r => r.role + ':' + r.pot.name + ' ' + r.pot.type + ' ΔE' + r.pot.dE + ' ' + r.pot.label).join(' | '));
